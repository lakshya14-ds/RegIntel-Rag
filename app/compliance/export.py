"""
Compliance Checklist Export Utilities (Phase 63.15).

Exports ComplianceChecklists to Markdown and JSON formats, preserving
exact source references, evidence quotes, and audit status.
"""

import json
from typing import Dict, Any
from app.compliance.models import ComplianceChecklist


def export_checklist_to_markdown(checklist: ComplianceChecklist) -> str:
    """Renders an executive compliance checklist document in Markdown."""
    checklist.recalculate_metrics()
    counts = checklist.summary_counts

    md = [
        f"# Regulatory Compliance Checklist: {checklist.title}",
        "",
        "> **Notice**: This document is generated by RegIntel RAG as a structured regulatory intelligence",
        "> aid. It does not constitute formal legal opinion or regulatory certification.",
        "",
        "## Summary & Progress",
        "",
        f"- **Checklist ID**: `{checklist.checklist_id}`",
        f"- **Authority**: {checklist.authority}",
        f"- **Regulatory Scope**: {checklist.regulatory_scope}",
        f"- **Checklist Completion Rate**: **{checklist.completion_rate}%**",
        f"- **Total Action Items**: {len(checklist.items)}",
        f"- **Breakdown**: Compliant: {counts.get('COMPLIANT', 0)} | Non-Compliant: {counts.get('NON_COMPLIANT', 0)} | Needs Review: {counts.get('NEEDS_REVIEW', 0)} | Not Reviewed: {counts.get('NOT_REVIEWED', 0)}",
        f"- **Last Updated**: {checklist.updated_at}",
        "",
        "---",
        "",
        "## Action Items & Controls",
        ""
    ]

    for idx, item in enumerate(checklist.items, 1):
        status_symbol = {
            "COMPLIANT": "✅ COMPLIANT",
            "NON_COMPLIANT": "❌ NON-COMPLIANT",
            "PARTIALLY_COMPLIANT": "⚠️ PARTIALLY COMPLIANT",
            "NEEDS_REVIEW": "🔍 NEEDS REVIEW",
            "NOT_APPLICABLE": "⚪ NOT APPLICABLE",
            "NOT_REVIEWED": "⏳ NOT REVIEWED",
            "UNKNOWN": "❓ UNKNOWN"
        }.get(item.status, item.status)

        md.append(f"### {idx}. {item.control_question}")
        md.append("")
        md.append(f"- **Status**: `{status_symbol}`")
        md.append(f"- **Expected Action**: {item.compliance_action}")
        md.append(f"- **Obligated Party**: {item.obligated_party or 'Regulated Entity'}")
        if item.deadline:
            md.append(f"- **Deadline**: `{item.deadline}`")
        if item.frequency:
            md.append(f"- **Frequency**: `{item.frequency}`")
        if item.applicability:
            md.append(f"- **Applicability**: {item.applicability}")

        if item.evidence_required:
            md.append(f"- **Required Evidence**: {', '.join(item.evidence_required)}")

        ref = item.source_reference
        if ref:
            sec_num = ref.get("section_number") or ""
            heading = ref.get("heading") or "General Provisions"
            page = ref.get("page_number")
            loc_str = f"Section {sec_num} ({heading})" if sec_num else heading
            if page:
                loc_str += f", Page {page}"
            md.append(f"- **Source Reference**: {loc_str}")
            snippet = ref.get("evidence_snippet")
            if snippet:
                md.append(f"  > *\"{snippet.strip()}\"*")

        if item.is_changed and item.change_summary:
            md.append(f"- ⚠️ **Recent Regulatory Change**: {item.change_summary}")

        if item.notes:
            md.append(f"- **Reviewer Notes**: {item.notes}")

        md.append("")
        md.append("---")
        md.append("")

    return "\n".join(md)


def export_checklist_to_json(checklist: ComplianceChecklist) -> str:
    """Serializes the complete checklist model to structured JSON."""
    checklist.recalculate_metrics()
    return json.dumps(checklist.model_dump(), indent=2, ensure_ascii=False)
